def app_find(t,x):
    for r in t:
        if r[3]>=x: return r[0]
    return '>'+str(t[-1][0])
def app(area,wall,I,drains=1,safety=20,slope=100):
    ea=area+wall*0.5; ct=ea*(I/100)*(1+safety/100); dc=ct/drains
    dch=dc/((100/slope)**0.5)
    return app_find(VT,dc),app_find(HT,dch),app_find(GT,dc)
